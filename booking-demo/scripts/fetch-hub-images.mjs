/**
 * One-off script: fetch images from example.com pages and emit imageManifest.ts.
 * Run: node scripts/fetch-hub-images.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const PUBLIC_IMAGES = path.join(ROOT, 'public', 'images');
const MANIFEST_PATH = path.join(ROOT, 'src', 'data', 'content', 'imageManifest.ts');

const LOGO_URL =
  'https://images.squarespace-cdn.com/content/v1/650028a254829f3a1ddef3de/1694509239679-0RQHWS5PGIPA8HV62MIR/Logos+2023.png?format=1500w';

const PAGES = [
  { key: 'home', url: 'https://example.com/', folder: 'home' },
  { key: 'events', url: 'https://example.com/events', folder: 'events' },
  { key: 'courses', url: 'https://example.com/courses', folder: 'courses' },
  { key: 'education', url: 'https://example.com/bespoke-education', folder: 'education' },
  { key: 'rentals', url: 'https://example.com/rentals', folder: 'rentals' },
  { key: 'compost', url: 'https://example.com/compost', folder: 'compost' },
  { key: 'kaiResilience', url: 'https://example.com/kai-resilience', folder: 'kai-resilience' },
  { key: 'volunteering', url: 'https://example.com/getting-involved', folder: 'volunteering' },
  { key: 'team', url: 'https://example.com/our-team', folder: 'team' },
  { key: 'about', url: 'https://example.com/about', folder: 'about' },
  { key: 'contact', url: 'https://example.com/contact', folder: 'contact' },
];

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function sanitizeFilename(name) {
  return name.replace(/[^a-zA-Z0-9._-]/g, '_').replace(/_+/g, '_').slice(0, 120);
}

function extractImageUrls(html) {
  const urls = new Set();
  const patterns = [
    /https:\/\/images\.squarespace-cdn\.com\/[^"'\s)]+/g,
    /https:\/\/static1\.squarespace\.com\/[^"'\s)]+/g,
  ];
  for (const pattern of patterns) {
    const matches = html.match(pattern) || [];
    for (let url of matches) {
      url = url.replace(/\\u002F/g, '/').replace(/&amp;/g, '&');
      if (url.includes('format=')) {
        url = url.split('?')[0] + '?format=1500w';
      }
      if (!url.includes('Logos+2023') || url.includes('format=')) {
        urls.add(url);
      }
    }
  }
  return [...urls];
}

async function downloadImage(url, destPath) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed ${url}: ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(destPath, buf);
}

function extFromUrl(url) {
  const base = url.split('?')[0];
  const ext = path.extname(base).toLowerCase();
  if (['.jpg', '.jpeg', '.png', '.gif', '.webp', '.svg'].includes(ext)) return ext;
  return '.jpg';
}

async function main() {
  ensureDir(PUBLIC_IMAGES);
  const manifest = {
    logo: '/images/logo.png',
    pages: {},
    sponsors: {},
  };

  // Logo
  console.log('Downloading logo...');
  await downloadImage(LOGO_URL, path.join(PUBLIC_IMAGES, 'logo.png'));

  for (const page of PAGES) {
    console.log(`Fetching ${page.url}...`);
    const res = await fetch(page.url);
    const html = await res.text();
    const urls = extractImageUrls(html);
    const folder = path.join(PUBLIC_IMAGES, page.folder);
    ensureDir(folder);

    const pageImages = [];
    let index = 0;
    for (const url of urls) {
      if (url.includes('Logos+2023')) continue;
      const ext = extFromUrl(url);
      const basename = sanitizeFilename(
        decodeURIComponent(path.basename(url.split('?')[0])) || `image-${index}`
      );
      const filename = `${String(index).padStart(2, '0')}-${basename}${ext.startsWith('.') ? '' : ext}`;
      const localPath = path.join(folder, filename);
      const publicPath = `/images/${page.folder}/${filename}`;

      try {
        await downloadImage(url, localPath);
        pageImages.push({ src: publicPath, alt: `${page.key} image ${index + 1}` });
        console.log(`  saved ${publicPath}`);
        index++;
      } catch (err) {
        console.warn(`  skip ${url}: ${err.message}`);
      }
    }
    manifest.pages[page.key] = pageImages;
  }

  // Emit manifest
  ensureDir(path.dirname(MANIFEST_PATH));
  const ts = `/** Auto-generated by scripts/fetch-hub-images.mjs — do not edit manually. */

export interface SiteImage {
  src: string;
  alt: string;
}

export const imageManifest = ${JSON.stringify(manifest, null, 2)} as const;

export function getPageImages(page: keyof typeof imageManifest.pages): SiteImage[] {
  return imageManifest.pages[page] ?? [];
}
`;
  fs.writeFileSync(MANIFEST_PATH, ts);
  console.log(`Wrote ${MANIFEST_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
